#!/usr/bin/env python3
"""Generate examples/tokei/stress.pie.

The workload exists to give the front end a large, ordinary Pride program:
hundreds of small functions with distinct local bindings, branches and calls,
so name lookup, local binding, branch folding and call resolution are exercised
at a scale no hand-written fixture reaches.

It is generated rather than checked in because the interesting property is the
COUNT, not the content. Every case has the same shape with different constants,
so 3229 committed lines encode 20 distinct behaviours -- the same coverage that
this script produces in ~150 lines. Committing the output again would put 3k
mechanical lines behind every future diff and inflate every line count.

Run `python3 tools/gen_tokei_stress.py` and commit the result if the shape
changes. Keep the output deterministic: the `stress_checksum` sentinel depends
on it.
"""
from pathlib import Path

CASES = 350
BATCH = 50

HEADER = """mod tokei.stress

-- Generated deterministic compile-time workload: hundreds of small, distinct
-- functions stress parsing, name lookup, local binding, branches and calls.
-- It is intentionally ordinary Pride source rather than generated binary data.
--
-- GENERATED by tools/gen_tokei_stress.py -- do not hand-edit. The point is the
-- number of functions, not their content; see that script for why this is not
-- checked in as 3k lines of near-duplicate source.
"""


def case(i: int) -> str:
    # Constants vary with i so the bodies are distinct trees, while the shape
    # stays fixed: a branch, a multiply, and an add the folds can attack.
    a, b, c, d = i + 1, (i % 7) + 3, (i % 11) + 5, (i % 3) + 2
    return f"""fn stress_case_{i:03d} : i64 -> i64
  | seed ->
      let offset_{i:03d} = seed + {a}i64
      let scaled_{i:03d} = offset_{i:03d} * {b}i64
      let chosen_{i:03d} = if scaled_{i:03d} > {a * b}i64 then scaled_{i:03d} - {c}i64 else scaled_{i:03d} + {d}i64
      let result_{i:03d} = chosen_{i:03d} + offset_{i:03d} * 2i64
      result_{i:03d}
"""


def batch(b: int) -> str:
    lo, hi = b * BATCH, min((b + 1) * BATCH, CASES)
    lines = [f"fn stress_batch_{b:02d} : i64 -> i64", "  | seed ->"]
    for i in range(lo, hi):
        lines.append(f"      let value_{i:03d} = stress_case_{i:03d}(seed)")
    lines.append("      " + " + ".join(f"value_{i:03d}" for i in range(lo, hi)))
    return "\n".join(lines) + "\n"


def checksum(nbatch: int) -> str:
    lines = ["fn stress_checksum : () -> i64", "  | () ->"]
    for b in range(nbatch):
        lines.append(f"      let batch_result_{b:02d} = stress_batch_{b:02d}({b + 1}i64)")
    lines.append("      " + " + ".join(f"batch_result_{b:02d}" for b in range(nbatch)))
    return "\n".join(lines) + "\n"


def main() -> None:
    nbatch = (CASES + BATCH - 1) // BATCH
    parts = [HEADER]
    parts.extend(case(i) for i in range(CASES))
    parts.extend(batch(b) for b in range(nbatch))
    parts.append(checksum(nbatch))
    out = Path(__file__).resolve().parents[1] / "examples" / "tokei" / "stress.pie"
    out.write_text("\n".join(parts), encoding="utf-8")
    print(f"wrote {out} ({CASES} cases, {nbatch} batches)")


if __name__ == "__main__":
    main()
